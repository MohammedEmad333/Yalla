function normalizeLanguage(language) {
  return language === 'en' ? 'en' : 'ar';
}

function t(language, key, variables = {}) {
  const value = key.split('.').reduce((entry, part) => entry && entry[part], COPY[normalizeLanguage(language)]);
  if (typeof value !== 'string') throw new Error('Unknown Telegram translation key: ' + key);
  return value.replace(/\{\{([a-zA-Z]+)\}\}/g, (_match, name) =>
    Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : '');
}

module.exports = { normalizeLanguage, t };
